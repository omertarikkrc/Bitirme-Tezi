function C = CBI_fcn(q)
   

   a1 = [1 - 2 * (q(3) ^ 2 + q(4) ^ 2), 2 * (q(2) * q(3) + q(1) * q(4)), 2 * (q(2) * q(4) - q(1) * q(3))];
   a2 = [2 * (q(2) * q(3) - q(1) * q(4)), 1 - 2 * (q(2) ^ 2 + q(4) ^ 2), 2 * (q(3) * q(4) + q(1) * q(2))];
   a3 = [2 * (q(2) * q(4) + q(1) * q(3)), 2 * (q(3) * q(4) - q(1) * q(2)), 1 - 2 * (q(2) ^ 2 + q(3) ^ 2)];

    C  = [a1; a2; a3];
end