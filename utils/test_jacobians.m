    if hata_fd < 1e-6,  d2 = 'UYUSTU'; else, d2 = 'KONTROL ET'; end
    fprintf('%-16s %-14.1e %-8s %-14.1e %s\n', ad{k}, hata_py, d1, hata_fd, d2);
