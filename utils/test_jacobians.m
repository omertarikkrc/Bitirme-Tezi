    % ölçekli nokta
    x = X{k};  x(1) = x(1)/M;  x(2:7) = x(2:7)/L;
    u = U{k};  u(1) = u(1)/(M*L);

    A = full(params_sc.A_func(x, u));          % 15x15
    B = full(params_sc.B_func(x, u));          % 15x5

    % (1) Python'a karşı: parmak izleri
    iz = {A*cx, A'*cx, B*cu, B'*cx};
    hata_py = 0;
    for j = 1:4
        hata_py = max(hata_py, max(abs(iz{j} - PY{k, j}) ./ max(abs(PY{k, j}), 1)));
    end

    % (2) merkezi sonlu farklar: (f(x+h) - f(x-h)) / 2h, her sütun için
    A_fd = zeros(15, 15);
    for j = 1:15
        e = zeros(15, 1);  e(j) = h;
        A_fd(:, j) = (dynamics(x + e, u, params_sc) - dynamics(x - e, u, params_sc))/(2*h);
    end
